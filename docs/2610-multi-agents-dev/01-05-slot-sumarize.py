def build_prompts(slots):
    prompt_head = f"""
        以下是一组用户与AI的对话内容，请基于所有上下文关系，总结出一个简洁摘要，突出用户的关注重点 \n\n
        对话内容如下：\n
    """
    slot_blocs = "\n".join(f"{i+1}.{text}" for i, text in enumerate(slots))

    prompt_tail = "\n请用一句话总结以上内容，要求涵盖关键信息且语言简洁准确"

    return prompt_head + slot_blocs + prompt_tail

